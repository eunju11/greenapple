-- 6. 소셜 로그인/회원가입 자동 프로필 생성 트리거 (handle_new_user)
-- ==============================================================================

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER AS $$
DECLARE
    v_full_name TEXT;
    v_avatar_url TEXT;
BEGIN
    -- 소셜 로그인 제공자별 메타데이터(카카오, 구글, 네이버 등) 추출
    v_full_name := COALESCE(
        NEW.raw_user_meta_data->>'full_name',
        NEW.raw_user_meta_data->>'name',
        NEW.raw_user_meta_data->>'user_name',
        split_part(NEW.email, '@', 1)
    );

    v_avatar_url := COALESCE(
        NEW.raw_user_meta_data->>'avatar_url',
        NEW.raw_user_meta_data->>'picture',
        NEW.raw_user_meta_data->>'profile_image'
    );

    INSERT INTO public.profiles (
        id,
        email,
        full_name,
        avatar_url,
        role,
        grade,
        total_spent,
        order_count
    ) VALUES (
        NEW.id,
        NEW.email,
        v_full_name,
        v_avatar_url,
        'customer',
        'BRONZE',
        0,
        0
    )
    ON CONFLICT (id) DO UPDATE SET
        email = EXCLUDED.email,
        full_name = COALESCE(public.profiles.full_name, EXCLUDED.full_name),
        avatar_url = COALESCE(public.profiles.avatar_url, EXCLUDED.avatar_url);

    RETURN NEW;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- auth.users 테이블에 회원가입 시 트리거 작동
DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
AFTER INSERT ON auth.users
FOR EACH ROW EXECUTE FUNCTION public.handle_new_user();


-- ==============================================================================
-- 7. 고객 등급 및 누적 구매금액/주문횟수 자동 갱신 함수 (update_customer_grade)
-- ==============================================================================

CREATE OR REPLACE FUNCTION public.update_customer_grade()
RETURNS TRIGGER AS $$
DECLARE
    v_target_user_id UUID;
    v_total_spent NUMERIC(12, 2) := 0;
    v_order_count INTEGER := 0;
    v_new_grade VARCHAR(20) := 'BRONZE';
BEGIN
    -- INSERT/UPDATE 시 대상 사용자 ID 지정
    IF (TG_OP = 'DELETE') THEN
        v_target_user_id := OLD.user_id;
    ELSE
        v_target_user_id := NEW.user_id;
    END IF;

    -- 실 결제완료/배송 단계의 주문 건에 대한 실 결제금액 및 주문 횟수 집계
    -- (paid, preparing, shipped, delivered 상태 기준)
    SELECT 
        COALESCE(SUM(final_amount), 0),
        COUNT(*)
    INTO 
        v_total_spent,
        v_order_count
    FROM public.orders
    WHERE user_id = v_target_user_id
      AND status IN ('paid', 'preparing', 'shipped', 'delivered')
      AND payment_status = 'completed';

    -- 완료된 환불 금액이 있다면 총 결제금액에서 차감
    SELECT 
        GREATEST(v_total_spent - COALESCE(SUM(r.refund_amount), 0), 0)
    INTO
        v_total_spent
    FROM public.refunds r
    WHERE r.user_id = v_target_user_id
      AND r.status = 'completed';

    -- 등급 산정 기준 (쇼핑몰 정책에 맞게 금액/횟수 커스텀 가능)
    -- VIP    : 총 결제 1,000,000원 이상 또는 주문 10회 이상
    -- GOLD   : 총 결제 500,000원 이상 또는 주문 5회 이상
    -- SILVER : 총 결제 200,000원 이상 또는 주문 2회 이상
    -- BRONZE : 기본 등급
    IF (v_total_spent >= 1000000 OR v_order_count >= 10) THEN
        v_new_grade := 'VIP';
    ELSIF (v_total_spent >= 500000 OR v_order_count >= 5) THEN
        v_new_grade := 'GOLD';
    ELSIF (v_total_spent >= 200000 OR v_order_count >= 2) THEN
        v_new_grade := 'SILVER';
    ELSE
        v_new_grade := 'BRONZE';
    END IF;

    -- 프로필 테이블 갱신
    UPDATE public.profiles
    SET 
        total_spent = v_total_spent,
        order_count = v_order_count,
        grade = v_new_grade,
        updated_at = timezone('utc'::text, now())
    WHERE id = v_target_user_id;

    RETURN NULL;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 주문 변경 시 고객 등급 갱신 트리거
DROP TRIGGER IF EXISTS trg_orders_update_grade ON public.orders;
CREATE TRIGGER trg_orders_update_grade
AFTER INSERT OR UPDATE OF status, payment_status, final_amount OR DELETE ON public.orders
FOR EACH ROW EXECUTE FUNCTION public.update_customer_grade();

-- 환불 상태 변경 시 고객 등급 갱신 트리거
DROP TRIGGER IF EXISTS trg_refunds_update_grade ON public.refunds;
CREATE TRIGGER trg_refunds_update_grade
AFTER INSERT OR UPDATE OF status, refund_amount OR DELETE ON public.refunds
FOR EACH ROW EXECUTE FUNCTION public.update_customer_grade();


